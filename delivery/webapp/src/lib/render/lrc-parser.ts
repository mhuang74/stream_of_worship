/**
 * LRC (LyRiCs) file parser for synchronized lyrics.
 * 
 * Parses LRC format: [mm:ss.xx] or [mm:ss.xxx] lyrics text
 * Supports both 2-digit and 3-digit millisecond precision.
 */

export interface LRCLine {
  /** Timestamp in seconds */
  timeSeconds: number;
  /** Lyric text */
  text: string;
}

export interface GlobalLRCLine {
  text: string;
  localTimeSeconds: number;
  globalTimeSeconds: number;
  title: string;
}

/**
 * Parse LRC file content into timestamped lines.
 * 
 * @param lrcContent - Raw LRC file content
 * @returns Array of LRC lines sorted by timestamp
 */
export function parseLRC(lrcContent: string): LRCLine[] {
  const lines: LRCLine[] = [];
  // Match [mm:ss.xx] or [mm:ss.xxx] format
  const pattern = /\[(\d{2}):(\d{2})\.(\d{2,3})\](.*)/;

  for (const line of lrcContent.split('\n')) {
    const match = pattern.exec(line.trim());
    if (match) {
      const minutes = parseInt(match[1], 10);
      const seconds = parseInt(match[2], 10);
      // Pad milliseconds to 3 digits if needed
      const milliseconds = parseInt(match[3].padEnd(3, '0').slice(0, 3), 10);
      const text = match[4].trim();

      const timeSeconds = minutes * 60 + seconds + milliseconds / 1000.0;
      // Empty-text lines are intentional placeholders: they blank the lyric
      // display during long instrumental gaps (gap markers generated by the
      // analysis pipeline). Keep them so the current-line lookup goes blank.
      lines.push({ timeSeconds, text });
    }
  }

  // Sort by timestamp
  return lines.sort((a, b) => a.timeSeconds - b.timeSeconds);
}

/**
 * Convert local LRC lines to global timeline.
 * 
 * @param localLines - LRC lines with local timestamps
 * @param segmentStartSeconds - Start time of this segment in the global timeline
 * @param title - Song title for these lyrics
 * @returns Array of global LRC lines
 */
export function convertToGlobalTimeline(
  localLines: LRCLine[],
  segmentStartSeconds: number,
  title: string
): GlobalLRCLine[] {
  return localLines.map((line) => ({
    text: line.text,
    localTimeSeconds: line.timeSeconds,
    globalTimeSeconds: segmentStartSeconds + line.timeSeconds,
    title,
  }));
}

/**
 * Estimate display duration for the last lyric line.
 * 
 * Uses two-tier approach:
 * 1. Primary: Match previous occurrence of same text in song
 * 2. Fallback: Character count + BPM estimation
 * 
 * @param songLyrics - All lyrics for the current song
 * @param tempoBpm - Song tempo in BPM (optional)
 * @returns Estimated duration in seconds (minimum 3s)
 */
export function estimateLastLyricDuration(
  songLyrics: GlobalLRCLine[],
  tempoBpm?: number | null
): number {
  if (songLyrics.length === 0) {
    return 5.0;
  }

  const lastLyric = songLyrics[songLyrics.length - 1];

  // Primary approach: find previous occurrence of same text
  for (let i = songLyrics.length - 2; i >= 0; i--) {
    if (songLyrics[i].text === lastLyric.text) {
      // Use the duration from the previous occurrence
      if (i + 1 < songLyrics.length) {
        const duration =
          songLyrics[i + 1].globalTimeSeconds - songLyrics[i].globalTimeSeconds;
        return Math.max(3.0, duration);
      }
    }
  }

  // Fallback approach: character count + BPM estimation
  const text = lastLyric.text;
  let charCount = 0;
  for (const char of text) {
    const code = char.charCodeAt(0);
    if (
      (code >= 0x4e00 && code <= 0x9fff) ||
      (code >= 0x3400 && code <= 0x4dbf) ||
      (code >= 0x3000 && code <= 0x303f)
    ) {
      charCount += 1.0;
    } else {
      charCount += 0.5;
    }
  }

  const bpm = tempoBpm && tempoBpm > 0 ? tempoBpm : 70.0;
  // Assume 2 beats per character for comfortable reading pace
  const beatsPerBeat = 60.0 / bpm;
  const duration = charCount * 2 * beatsPerBeat;

  return Math.max(3.0, duration);
}

/**
 * Find the current lyric index based on time.
 * 
 * @param lyrics - Array of LRC lines
 * @param currentTimeSeconds - Current playback time
 * @returns Index of current lyric, or -1 if before first lyric
 */
export function findCurrentLyricIndex(
  lyrics: GlobalLRCLine[],
  currentTimeSeconds: number
): number {
  let currentIndex = -1;
  for (let i = 0; i < lyrics.length; i++) {
    if (lyrics[i].globalTimeSeconds <= currentTimeSeconds) {
      currentIndex = i;
    } else {
      break;
    }
  }
  return currentIndex;
}

/**
 * Group lyrics by song title for easy lookup.
 * 
 * @param lyrics - Array of global LRC lines
 * @returns Map of title to lyrics array
 */
export function groupLyricsBySong(
  lyrics: GlobalLRCLine[]
): Map<string, GlobalLRCLine[]> {
  const grouped = new Map<string, GlobalLRCLine[]>();
  for (const line of lyrics) {
    if (!grouped.has(line.title)) {
      grouped.set(line.title, []);
    }
    grouped.get(line.title)!.push(line);
  }
  return grouped;
}

/**
 * Validate LRC content format.
 * 
 * @param lrcContent - Raw LRC file content
 * @returns True if valid LRC format
 */
export function isValidLRC(lrcContent: string): boolean {
  const pattern = /\[\d{2}:\d{2}\.\d{2,3}\]/;
  let matchCount = 0;
  for (const line of lrcContent.split('\n')) {
    if (pattern.test(line)) {
      matchCount++;
      if (matchCount >= 2) {
        return true;
      }
    }
  }
  return false;
}

/**
 * Get the time range for lyrics display.
 * 
 * @param lyrics - Array of LRC lines
 * @returns Object with first and last lyric times, or null if empty
 */
export function getLyricsTimeRange(
  lyrics: LRCLine[]
): { firstTime: number; lastTime: number } | null {
  if (lyrics.length === 0) {
    return null;
  }
  return {
    firstTime: lyrics[0].timeSeconds,
    lastTime: lyrics[lyrics.length - 1].timeSeconds,
  };
}

/**
 * Beats of source audio a lyric onset may precede a Step's start before
 * ownership is refused, and the slack by which a Step's end may still cover its
 * last line's display. Section bounds are beat-snapped while LRC onsets come
 * from forced alignment, so a pickup phrase can start up to a beat or two
 * before the section it is sung into.
 */
export const LYRIC_BOUNDARY_TOLERANCE_BEATS = 2;

/**
 * Tolerance used when the Recording has no usable tempo (no analysis), i.e. the
 * pre-tempo fixed bound.
 */
export const FALLBACK_LYRIC_BOUNDARY_TOLERANCE_SECONDS = 0.5;

/** Two beats at the Recording's tempo, or the fixed fallback without one. */
export function lyricBoundaryToleranceSeconds(
  tempoBpm: number | null | undefined
): number {
  if (tempoBpm === null || tempoBpm === undefined) {
    return FALLBACK_LYRIC_BOUNDARY_TOLERANCE_SECONDS;
  }
  if (!Number.isFinite(tempoBpm) || tempoBpm <= 0) {
    return FALLBACK_LYRIC_BOUNDARY_TOLERANCE_SECONDS;
  }
  return (LYRIC_BOUNDARY_TOLERANCE_BEATS * 60) / tempoBpm;
}

/**
 * For each line, the timestamp at which its lyric display ends: the following
 * line's timestamp, or the line's own timestamp when it is the final line.
 *
 * `lines` MUST be sorted ascending by `timeSeconds`, as {@link parseLRC}
 * returns them.
 */
export function lyricLineEndSeconds(lines: readonly LRCLine[]): number[] {
  return lines.map((line, index) => lines[index + 1]?.timeSeconds ?? line.timeSeconds);
}

/** A half-open `[startSeconds, endSeconds)` run of the source recording. */
export interface TimeWindow {
  startSeconds: number;
  endSeconds: number;
}

const OWNER_EPSILON = 1e-9;

/**
 * Whether `window` is a candidate owner for one line: its onset is at or after
 * `start - tolerance`, and either the onset is more than `tolerance` before the
 * window's end (sung inside the cut regardless of when its display ends) or the
 * line's display end is within `tolerance` of the end (the window covers the
 * display). Zero-length windows are never candidates.
 */
function isOwnerCandidate(
  window: TimeWindow,
  timeSeconds: number,
  lineEndSeconds: number,
  tolerance: number
): boolean {
  if (!(window.endSeconds > window.startSeconds)) return false;
  if (timeSeconds < window.startSeconds - tolerance) return false;
  if (
    timeSeconds >= window.endSeconds - tolerance &&
    lineEndSeconds >= window.endSeconds + tolerance
  ) {
    return false;
  }
  return true;
}

/**
 * Whether two windows begin at the same source time. A repeated Step shares its
 * start with its twin even after either end is nudged, and both sing the same
 * region, so ownership must not be exclusive between them.
 */
function sameSourceStart(a: TimeWindow, b: TimeWindow): boolean {
  return Math.abs(a.startSeconds - b.startSeconds) <= OWNER_EPSILON;
}

/**
 * Index of the window that owns a lyric line, or -1.
 *
 * A window is a candidate when the line's onset `timeSeconds` is at or after
 * `start - tolerance`, and either
 *
 * - the onset is more than `tolerance` before the window's end, so the line is
 *   sung inside the cut regardless of when its display ends, or
 * - the line's display end `lineEndSeconds` is less than `end + tolerance`,
 *   i.e. the window covers the display.
 *
 * The second branch is what refuses the following section's first line: a line
 * that merely starts at or just after the end is sung after the cut, so the cut
 * never plays it. `lineEndSeconds` comes from {@link lyricLineEndSeconds}.
 *
 * Among candidates the window with the nearest *start* wins: LRC onsets come
 * from forced alignment while section bounds are beat-snapped, so a pickup
 * starts a fraction before the section it is sung into, and a line *inside* a
 * section still belongs to that section. Ties resolve to the greater start,
 * then the greater end, then the lowest index. Windows with
 * `endSeconds <= startSeconds` are never candidates. Windows that begin at the
 * same source time are never exclusive: the caller decides inclusion by start,
 * so a repeated range and its twin both display the line.
 *
 * `tolerance` is the tempo-derived bound a caller gets from
 * {@link lyricBoundaryToleranceSeconds}; it defaults to the no-tempo fallback.
 */
export function nearestStartOwnerIndex(
  windows: readonly TimeWindow[],
  timeSeconds: number,
  lineEndSeconds: number,
  tolerance: number = FALLBACK_LYRIC_BOUNDARY_TOLERANCE_SECONDS
): number {
  let best = -1;
  let bestDistance = Number.POSITIVE_INFINITY;
  for (let index = 0; index < windows.length; index += 1) {
    const window = windows[index]!;
    if (!isOwnerCandidate(window, timeSeconds, lineEndSeconds, tolerance)) continue;
    const distance = Math.abs(timeSeconds - window.startSeconds);
    if (best === -1 || distance < bestDistance - OWNER_EPSILON) {
      best = index;
      bestDistance = distance;
      continue;
    }
    if (Math.abs(distance - bestDistance) > OWNER_EPSILON) continue;
    const current = windows[best]!;
    if (window.startSeconds > current.startSeconds + OWNER_EPSILON) {
      best = index;
    } else if (
      Math.abs(window.startSeconds - current.startSeconds) <= OWNER_EPSILON &&
      window.endSeconds > current.endSeconds + OWNER_EPSILON
    ) {
      best = index;
    }
  }
  return best;
}

/**
 * LRC lines belonging to one Step's source range.
 *
 * Ownership is decided globally by {@link nearestStartOwnerIndex}: a line is a
 * candidate for the windows whose start and end bounds it falls within
 * `toleranceSeconds` of, and the window with the nearest start keeps it.
 * `toleranceSeconds` is two beats at the Recording's tempo
 * ({@link lyricBoundaryToleranceSeconds}). A pickup sung just before a Step
 * therefore lands on that Step even when the section between them was omitted
 * from the arrangement, while the following section's first line is refused
 * unless the Step covers its display: a line starting at or just after the
 * Step's end is sung after the cut and is never played. A line starting more
 * than two beats before the end is always kept, so a cut that ends inside an
 * instrumental gap keeps its last line.
 *
 * A Step keeps a line when its own window is a candidate for it **and** the
 * owner's start equals its own start, so a Step shows only what its own cut
 * plays and a trimmed repeat never inherits a line past its own end.
 * Consecutive Steps tile: with `end_i == start_{i+1}` no line is owned twice
 * and none silently disappears — a shared boundary pickup appears once, under
 * the later Step. A repeated Step shows its lines again even when its own end
 * differs from its twin's, because a repeat is the same source region and
 * ownership is not exclusive between windows that begin together.
 *
 * @param lines - Parsed LRC lines for the whole recording, sorted ascending by
 *   `timeSeconds` as {@link parseLRC} returns them
 * @param startSeconds - Source start of the Step
 * @param endSeconds - Source end of the Step
 * @param siblings - Every Step in the same draft. Omit for a standalone range
 *   with no neighbours.
 * @param toleranceSeconds - How far outside a Step's bounds an onset may sit and
 *   still belong to it: two beats at the Recording's tempo.
 * @returns The subset of lines assigned to this Step
 */
export function linesForSourceRange(
  lines: LRCLine[],
  startSeconds: number,
  endSeconds: number,
  siblings: ReadonlyArray<TimeWindow> = [],
  toleranceSeconds: number = FALLBACK_LYRIC_BOUNDARY_TOLERANCE_SECONDS
): LRCLine[] {
  if (!(endSeconds > startSeconds)) return [];
  const self: TimeWindow = { startSeconds, endSeconds };
  const windows: TimeWindow[] = siblings.filter((w) => w.endSeconds > w.startSeconds);
  // Exact-identity dedupe only: a same-start sibling with a different end must
  // not replace the requested window, or a trimmed Step would lose the lines
  // between its own end and the sibling's.
  const sameWindow = (w: TimeWindow) =>
    sameSourceStart(w, self) && Math.abs(w.endSeconds - endSeconds) <= OWNER_EPSILON;
  if (!windows.some(sameWindow)) windows.push(self);
  const lineEnds = lyricLineEndSeconds(lines);
  return lines.filter((line, index) => {
    const lineEnd = lineEnds[index]!;
    // A Step shows only what its own cut plays (the same two-beat slack as any
    // other Step), then accepts a line another Step owns only when that Step
    // begins where this one does: a repeated Step is the same source region, so
    // the twin's greater end must not take the section's lines away from it.
    if (!isOwnerCandidate(self, line.timeSeconds, lineEnd, toleranceSeconds)) return false;
    const owner = nearestStartOwnerIndex(windows, line.timeSeconds, lineEnd, toleranceSeconds);
    return owner >= 0 && sameSourceStart(windows[owner]!, self);
  });
}
